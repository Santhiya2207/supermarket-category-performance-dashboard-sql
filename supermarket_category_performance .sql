-- 5.2.1 Category performance: quantity, revenue, cost, profit,
--       profit margin and revenue contribution
SELECT
    c.category_name,
    SUM(si.quantity)                                                                      AS total_quantity_sold,
    ROUND(SUM(si.quantity * si.selling_price), 2)                                         AS total_revenue,
    ROUND(SUM(si.quantity * si.cost_price), 2)                                            AS total_cost,
    ROUND(SUM(si.quantity * (si.selling_price - si.cost_price)), 2)                       AS total_profit,
    ROUND(SUM(si.quantity * (si.selling_price - si.cost_price))
