JOIN categories c ON p.category_id = c.category_id
GROUP BY c.category_id, c.category_name
ORDER BY revenue_rank;

-- 5.8.2 Rank products based on profit within their own category
SELECT category_name, product_name, total_profit, profit_rank_in_category
FROM (
    SELECT
        c.category_name,
        p.product_name,
        ROUND(SUM(si.quantity * (si.selling_price - si.cost_price)), 2) AS total_profit,
        RANK() OVER (PARTITION BY c.category_id
                     ORDER BY SUM(si.quantity * (si.selling_price - si.cost_price)) DESC) AS profit_rank_in_category
    FROM sale_items si
    JOIN products p   ON si.product_id = p.product_id
    JOIN categories c ON p.category_id = c.category_id
    GROUP BY c.category_id, c.category_name, p.product_id, p.product_name
) ranked_products
WHERE profit_rank_in_category <= 3
ORDER BY category_name, profit_rank_in_category;

-- 5.8.3 Compare current-month revenue with previous-month revenue
--       (with growth label)
WITH monthly_revenue AS (
    SELECT DATE_FORMAT(s.sale_date, '%Y-%m') AS sale_month,
           SUM(si.quantity * si.selling_price) AS revenue
    FROM sales s
    JOIN sale_items si ON s.sale_id = si.sale_id
    GROUP BY DATE_FORMAT(s.sale_date, '%Y-%m')
),
monthly_compare AS (
    SELECT sale_month,
           revenue,
           LAG(revenue) OVER (ORDER BY sale_month) AS previous_revenue
    FROM monthly_revenue
)
SELECT
    sale_month,
    ROUND(revenue, 2)          AS current_month_revenue,
    ROUND(previous_revenue, 2) AS previous_month_revenue,
    ROUND((revenue - previous_revenue) / previous_revenue * 100, 2) AS mom_growth_pct,
    CASE
        WHEN previous_revenue IS NULL     THEN 'First Month'
        WHEN revenue > previous_revenue   THEN 'Growth'
        WHEN revenue < previous_revenue   THEN 'Decline'
        ELSE 'No Change'
    END AS trend
FROM monthly_compare
ORDER BY sale_month;

