-- 5.8.1 Rank categories based on revenue (with profit margin and revenue contribution)
SELECT
    RANK() OVER (ORDER BY SUM(si.quantity * si.selling_price) DESC)                  AS revenue_rank,
    c.category_name,
    ROUND(SUM(si.quantity * si.selling_price), 2)                                    AS total_revenue,
    ROUND(SUM(si.quantity * (si.selling_price - si.cost_price))
